pub(super) const GRAY_LUT_LEN: usize = 42;

const fn lut(prefix: [u8; 12]) -> [u8; GRAY_LUT_LEN] {
    let mut result = [0u8; GRAY_LUT_LEN];

    let mut index = 0;

    while index < prefix.len() {
        result[index] = prefix[index];
        index += 1;
    }

    result
}

